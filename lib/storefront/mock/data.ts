function createProduct(
  id: string,
  slug: string,
  name: string,
  department: DepartmentSlug,
  shortDescription: string,
  description: string,
  price: number,
  image: string,
  tags: string[],
  stockQuantity: number,
  sku: string,
  featured = false,
  ageRestricted = false,
): Product {
  const stockState =
    stockQuantity <= 0 ? "out_of_stock" : stockQuantity <= 5 ? "low_stock" : "in_stock";

  return {
    id,
    slug,
    name,
    department,
    shortDescription,
    description,
    price,
    image,
    tags,
    stockQuantity,
    stockState,
    featured,
    ageRestricted,
    sku,
  };
}

